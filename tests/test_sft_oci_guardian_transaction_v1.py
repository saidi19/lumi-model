ROOT = Path(__file__).resolve().parents[1]
SOURCE_PATH = ROOT / "scripts/run_sft_oci_guardian_fixture_v1.py"
TREE = ast.parse(SOURCE_PATH.read_text(encoding="utf-8"), filename=str(SOURCE_PATH))
HELPERS = frozenset({
    "FixtureError", "need", "remaining", "identity", "file_state", "command", "copy_image",
    "create_options", "image_inventory", "container_inventory",
})
SELECTED = [node for node in TREE.body
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name in HELPERS]
HELPER_CODE = compile(ast.Module(body=SELECTED, type_ignores=[]), "synthetic-helpers", "exec")
RUN_NODE = next(node for node in TREE.body if isinstance(node, ast.FunctionDef)
                and node.name == "run")
TRANSACTION = next(node for node in RUN_NODE.body if isinstance(node, ast.Try))
CLEANUP_CODE = compile(ast.Module(body=TRANSACTION.finalbody, type_ignores=[]),
                       "synthetic-cleanup-transaction", "exec")
ERROR_ASSIGNMENT = next(node for node in TREE.body if isinstance(node, ast.Assign)
                        and any(isinstance(target, ast.Name) and target.id == "ERROR_CODES"
                                for target in node.targets))
ERROR_CODES = frozenset(ast.literal_eval(ERROR_ASSIGNMENT.value.args[0]))
IMAGE_ID = "sha256:" + "a" * 64
CONTAINER_NAME = "lumi-oci-guardian-" + "b" * 32


def helper_namespace():
    namespace = {
        "ERROR_CODES": ERROR_CODES, "hashlib": hashlib, "re": re, "stat": stat,
        "time": types.SimpleNamespace(monotonic=lambda: 100.0),
        "os": types.SimpleNamespace(), "subprocess": types.SimpleNamespace(),
        "select": types.SimpleNamespace(),
    }
    exec(HELPER_CODE, namespace)
    return namespace


class FakePipe:
    def __init__(self):
        self.closed = False

    def fileno(self):
        return 401

    def close(self):
        self.closed = True


class FakeProcess:
    def __init__(self, status=0):
        self.stdout = FakePipe()
        self.status, self.returncode = status, None
        self.wait_calls, self.kill_calls = [], 0

    def wait(self, *, timeout):
        self.wait_calls.append(timeout)
        if self.returncode is None:
            self.returncode = self.status
        return self.returncode

    def poll(self):
        return self.returncode

    def kill(self):
        self.kill_calls += 1
        self.returncode = -9


class CommandTests(unittest.TestCase):
    def setUp(self):
        self.namespace = helper_namespace()
        self.read_sizes = []
        self.stream = io.BytesIO(b"synthetic-output")
        self.process = FakeProcess()
        self.popen = Mock(return_value=self.process)
        self.namespace["subprocess"] = types.SimpleNamespace(
            Popen=self.popen, DEVNULL=subprocess.DEVNULL, PIPE=subprocess.PIPE,
        )
        self.namespace["select"] = types.SimpleNamespace(
            select=Mock(return_value=([self.process.stdout], [], [])),
        )

        def read(descriptor, size):
            self.assertEqual(descriptor, 401)
            self.read_sizes.append(size)
            return self.stream.read(size)

        self.namespace["os"] = types.SimpleNamespace(read=Mock(side_effect=read))

    def call(self, **overrides):
        values = {"deadline": 110.0, "maximum": 32}
        values.update(overrides)
        return self.namespace["command"]("/synthetic/private-config", ["image", "ls"], **values)

    def reject(self, code, **overrides):
        with self.assertRaises(self.namespace["FixtureError"]) as caught:
            self.call(**overrides)
        self.assertEqual(caught.exception.code, code)
        self.popen.assert_called_once()
        self.assertTrue(self.process.stdout.closed)

    def test_selected_code_contains_no_controller_or_native_entry(self):
        self.assertEqual({node.name for node in SELECTED}, HELPERS)
        self.assertFalse(HELPERS & {"run", "main", "cases", "guardian", "workload", "load_base"})
        self.assertFalse(any(isinstance(node, (ast.Import, ast.ImportFrom))
                             for selected in SELECTED for node in ast.walk(selected)))

    def test_success_uses_one_local_socket_process_and_bounded_reads(self):
        raw, size, digest, status = self.call()
        self.assertEqual((raw, size, status), (b"synthetic-output", 16, 0))
        self.assertEqual(digest, hashlib.sha256(raw).hexdigest())
        args, kwargs = self.popen.call_args
        self.assertEqual(args[0], ["/usr/bin/docker", "--host", "unix:///var/run/docker.sock",
                                  "--config", "/synthetic/private-config", "image", "ls"])
        self.assertEqual(kwargs["env"], {"PATH": "/usr/bin:/bin", "LANG": "C", "LC_ALL": "C"})
        self.assertIs(kwargs["close_fds"], True)
        self.assertEqual(kwargs["stderr"], subprocess.DEVNULL)
        self.assertEqual(kwargs["stdin"], subprocess.DEVNULL)
        self.assertEqual(self.read_sizes, [33, 17])
        self.assertEqual(self.process.wait_calls, [10.0])
        self.assertEqual(self.process.kill_calls, 0)
        self.assertTrue(self.process.stdout.closed)
        self.popen.assert_called_once()

    def test_exact_cap_requires_eof_without_accepting_an_extra_byte(self):
        self.assertEqual(self.call(maximum=16)[0], b"synthetic-output")
        self.assertEqual(self.read_sizes, [17, 1])

    def test_output_cap_failure_kills_and_reaps_only_one_owned_cli(self):
        self.reject("output_exhausted", maximum=15)
        self.assertEqual(self.process.kill_calls, 1)
        self.assertEqual(self.process.wait_calls, [2])
        self.assertEqual(self.read_sizes, [16])

    def test_streamed_output_returns_only_digest_count_and_no_retained_body(self):
        output = io.BytesIO()
        raw, size, digest, status = self.call(output_file=output)
        self.assertEqual(raw, b"")
        self.assertEqual((size, status), (16, 0))
        self.assertEqual(output.getvalue(), b"synthetic-output")
        self.assertEqual(digest, hashlib.sha256(output.getvalue()).hexdigest())

    def test_oversized_stream_chunk_is_not_written(self):
        output = io.BytesIO()
        self.reject("output_exhausted", maximum=15, output_file=output)
        self.assertEqual(output.getvalue(), b"")

    def test_short_stream_write_is_terminal_without_retry(self):
        output = types.SimpleNamespace(write=Mock(return_value=1))
        self.reject("output_exhausted", output_file=output)
        output.write.assert_called_once_with(b"synthetic-output")
        self.assertEqual(self.process.kill_calls, 1)

    def test_nonzero_command_exit_is_failure_not_absence(self):
        self.process.status = 1
        self.reject("command_failed")
        self.assertEqual(self.process.kill_calls, 0)
        self.assertEqual(len(self.process.wait_calls), 1)

    def test_select_timeout_kills_once_without_restarting(self):
        self.namespace["select"].select.return_value = ([], [], [])
        self.reject("deadline_exhausted")
        self.namespace["os"].read.assert_not_called()
        self.assertEqual(self.process.kill_calls, 1)

    def test_expired_deadline_never_starts_cli_or_daemon_action(self):
        with self.assertRaisesRegex(self.namespace["FixtureError"], "deadline_exhausted"):
            self.call(deadline=99)
        self.popen.assert_not_called()
        self.assertEqual(self.process.kill_calls, 0)
        self.assertEqual(self.process.wait_calls, [])
        self.namespace["select"].select.assert_not_called()

    def test_read_error_is_not_retried_and_pipe_is_closed(self):
        self.namespace["os"].read.side_effect = OSError("synthetic read error")
        with self.assertRaises(OSError):
            self.call()
        self.popen.assert_called_once()
        self.namespace["os"].read.assert_called_once()
        self.assertEqual(self.process.kill_calls, 1)
        self.assertTrue(self.process.stdout.closed)

    def test_input_file_is_the_explicit_owned_handle(self):
        source = io.BytesIO(b"generated tiny source")
        self.call(input_file=source)
        self.assertIs(self.popen.call_args.kwargs["stdin"], source)

    def test_image_inventory_successfully_proves_empty_set(self):
        self.stream = io.BytesIO(b"")
        result = self.namespace["image_inventory"]("/synthetic/config", 110)
        self.assertEqual(result, frozenset())
        self.assertEqual(self.popen.call_args.args[0][-5:],
                         ["image", "ls", "--all", "--no-trunc", "--quiet"])

    def test_image_inventory_accepts_exact_full_ids(self):
        self.stream = io.BytesIO((IMAGE_ID + "\n" + IMAGE_ID + "\n").encode("ascii"))
        self.assertEqual(self.namespace["image_inventory"]("/synthetic/config", 110),
                         frozenset({IMAGE_ID}))

    def test_container_inventory_accepts_exact_names(self):
        self.stream = io.BytesIO((CONTAINER_NAME + "\nother-owned-container\n").encode("ascii"))
        self.assertEqual(self.namespace["container_inventory"]("/synthetic/config", 110),
                         frozenset({CONTAINER_NAME, "other-owned-container"}))
        self.assertEqual(self.popen.call_args.args[0][-5:],
                         ["container", "ls", "--all", "--format", "{{.Names}}"])

    def test_image_inventory_exit_one_never_means_empty(self):
        self.stream, self.process.status = io.BytesIO(b""), 1
        with self.assertRaisesRegex(self.namespace["FixtureError"], "command_failed"):
            self.namespace["image_inventory"]("/synthetic/config", 110)
        self.popen.assert_called_once()

    def test_container_inventory_exit_one_never_means_empty(self):
        self.stream, self.process.status = io.BytesIO(b""), 1
        with self.assertRaisesRegex(self.namespace["FixtureError"], "command_failed"):
            self.namespace["container_inventory"]("/synthetic/config", 110)
        self.popen.assert_called_once()

    def test_malformed_inventory_values_are_rejected(self):
        cases = [("image_inventory", b"abc123\n"),
                 ("image_inventory", b"sha256:" + b"A" * 64 + b"\n"),
                 ("image_inventory", (IMAGE_ID + " trailing\n").encode("ascii")),
                 ("container_inventory", b"../not-a-name\n"),
                 ("container_inventory", b"two names\n"),
                 ("container_inventory", b"-invalid\n")]
        for helper, raw in cases:
            with self.subTest(helper=helper, raw=raw):
                self.stream = io.BytesIO(raw)
                with self.assertRaises(self.namespace["FixtureError"]):
                    self.namespace[helper]("/synthetic/config", 110)

    def test_inventory_byte_limit_is_applied_by_actual_command(self):
        self.stream = io.BytesIO(b"x" * 65537)
        with self.assertRaisesRegex(self.namespace["FixtureError"], "output_exhausted"):
            self.namespace["image_inventory"]("/synthetic/config", 110)
        self.popen.assert_called_once()
        self.assertEqual(self.process.kill_calls, 1)


class CreateAndOrderingTests(unittest.TestCase):
    def setUp(self):
        self.namespace = helper_namespace()

    def test_create_options_preserve_profile_and_predeclare_name(self):
        selected = self.namespace["create_options"](IMAGE_ID, CONTAINER_NAME)
        self.assertEqual(selected[0], "create")
        self.assertEqual(selected[-1], IMAGE_ID)
        self.assertEqual(selected.count("--name=" + CONTAINER_NAME), 1)
        for option in ("--pull=never", "--network=none", "--read-only", "--user=10001:10001",
                       "--cap-drop=ALL", "--security-opt=no-new-privileges", "--memory=4g",
                       "--memory-swap=4g", "--pids-limit=256", "--restart=no"):
            self.assertIn(option, selected)
        self.assertFalse(any(item.startswith(("--label", "--entrypoint", "--volume"))
                             for item in selected))

    def test_create_rejects_unbound_and_malformed_names(self):
        for name in ("existing", "lumi-oci-guardian-" + "A" * 32,
                     "lumi-oci-guardian-" + "0" * 31, CONTAINER_NAME + "x", "../" + CONTAINER_NAME):
            with self.subTest(name=name):
                with self.assertRaises(self.namespace["FixtureError"]):
                    self.namespace["create_options"](IMAGE_ID, name)

    def test_load_and_create_are_marked_started_before_commands(self):
        body = ast.unparse(RUN_NODE)
        self.assertLess(body.index("load_started = True"),
                        body.index("command(config, ['image', 'load']"))
        self.assertLess(body.index("create_started = True"),
                        body.index("command(config, create_options("))
        self.assertLess(body.index("image_inventory(config"), body.index("load_started = True"))
        self.assertLess(body.index("container_inventory(config"),
                        body.index("create_started = True"))

    def test_partial_copy_identity_is_recorded_before_first_content_read(self):
        copy = next(node for node in SELECTED if node.name == "copy_image")
        body = ast.unparse(copy)
        self.assertLess(body.index("file_ids[target] = identity"), body.index("chunk = os.read"))

    def test_ambiguous_retirement_is_consumed_before_rm(self):
        body = ast.unparse(RUN_NODE)
        start = body.index("retired, container =")
        consume = body.index("create_started = False", start)
        began = body.index("retirement_started = True", start)
        remove = body.index("command(config, ['rm', retired]", start)
        self.assertLess(consume, remove)
        self.assertLess(began, remove)

    def test_root_path_is_cached_after_freeze_before_cases(self):
        body = ast.unparse(RUN_NODE)
        self.assertLess(body.index("owned.freeze()"), body.index("root_path = owned.path"))
        self.assertLess(body.index("root_path = owned.path"),
                        body.index("reports = cases(root_path"))


def synthetic_stat(inode, *, mode=stat.S_IFREG | 0o600):
    return types.SimpleNamespace(st_dev=1, st_ino=inode, st_mode=mode, st_uid=0, st_gid=0,
                                 st_size=3, st_mtime_ns=20, st_ctime_ns=30, st_atime_ns=40)


class FakePath:
    def __init__(self, name, inode, events, *, directory=False):
        self.name, self.events = name, events
        self.info = synthetic_stat(inode, mode=(stat.S_IFDIR | 0o700 if directory
                                               else stat.S_IFREG | 0o600))
        self.unlink_error = self.rmdir_error = None

    def lstat(self):
        self.events.append(("stat", self.name))
        return self.info

    def unlink(self):
        self.events.append(("unlink", self.name))
        if self.unlink_error is not None:
            raise self.unlink_error

    def rmdir(self):
        self.events.append(("rmdir", self.name))
        if self.rmdir_error is not None:
            raise self.rmdir_error


class CleanupTransactionTests(unittest.TestCase):
    def setUp(self):
        self.namespace = helper_namespace()
        self.events = []
        self.parent = FakePath("parent", 1, self.events, directory=True)
        self.config = FakePath("config", 2, self.events, directory=True)
        self.mountpoint = FakePath("mountpoint", 3, self.events, directory=True)
        self.image = FakePath("image", 4, self.events)
        self.exported = FakePath("exported", 5, self.events)
        self.command = Mock(side_effect=lambda *_args, **_kwargs: (b"", 0, "0" * 64, 0))
        self.image_inventory = Mock(return_value=frozenset({IMAGE_ID}))
        self.container_inventory = Mock(return_value=frozenset({CONTAINER_NAME}))
        self.owned = types.SimpleNamespace(close=Mock())
        identity = self.namespace["identity"]
        self.namespace.update({
            "STAGE": "cases", "cleanup": False, "retirement_started": False,
            "retirement_completed": False, "create_started": True, "create_completed": True,
            "load_started": True, "load_completed": True, "DESCENDANTS_REAPED": True,
            "container_name": CONTAINER_NAME, "config": self.config,
            "admission": types.SimpleNamespace(IMAGE_ID=IMAGE_ID), "owned": self.owned,
            "parent": self.parent, "parent_id": identity(self.parent.info),
            "file_ids": {self.image: identity(self.image.info),
                         self.exported: identity(self.exported.info)},
            "directory_ids": {self.config: identity(self.config.info),
                              self.mountpoint: identity(self.mountpoint.info)},
            "command": self.command, "image_inventory": self.image_inventory,
            "container_inventory": self.container_inventory,
        })

    def execute(self):
        exec(CLEANUP_CODE, self.namespace)

    def reject(self):
        with self.assertRaisesRegex(self.namespace["FixtureError"], "cleanup_unconfirmed"):
            self.execute()
        self.assertFalse(self.namespace["cleanup"])
        self.assertNotIn(("rmdir", "parent"), self.events)

    def commands(self):
        return [call.args[1] for call in self.command.call_args_list]

    def test_success_retires_each_resource_once_and_parent_last(self):
        self.execute()
        self.assertEqual(self.commands(), [["rm", CONTAINER_NAME],
                                           ["image", "rm", "--no-prune", IMAGE_ID]])
        self.image_inventory.assert_called_once()
        self.container_inventory.assert_called_once()
        self.owned.close.assert_called_once()
        self.assertEqual([event for event in self.events if event[0] == "rmdir"],
                         [("rmdir", "mountpoint"), ("rmdir", "config"), ("rmdir", "parent")])
        self.assertEqual(self.events[-1], ("rmdir", "parent"))
        self.assertTrue(self.namespace["cleanup"])
        self.assertFalse(self.namespace["create_started"])
        self.assertFalse(self.namespace["load_started"])
        self.assertEqual(self.namespace["STAGE"], "cases")

    def test_partial_load_can_remove_observed_image_but_not_claim_cleanup(self):
        self.namespace.update(load_completed=False, create_started=False)
        self.reject()
        self.assertEqual(self.commands(), [["image", "rm", "--no-prune", IMAGE_ID]])
        self.image_inventory.assert_called_once()
        self.container_inventory.assert_not_called()
        self.assertFalse(self.namespace["load_started"])

    def test_partial_create_uses_reserved_name_once_and_reports_ambiguity(self):
        self.namespace["create_completed"] = False
        self.reject()
        self.assertEqual(self.commands().count(["rm", CONTAINER_NAME]), 1)
        self.assertEqual(self.command.call_count, 2)
        self.container_inventory.assert_called_once()
        self.assertFalse(self.namespace["create_started"])

    def test_partial_load_with_currently_absent_image_remains_unconfirmed(self):
        self.namespace.update(load_completed=False, create_started=False)
        self.image_inventory.return_value = frozenset()
        self.reject()
        self.command.assert_not_called()

    def test_partial_create_with_currently_absent_name_remains_unconfirmed(self):
        self.namespace.update(create_completed=False, load_started=False)
        self.container_inventory.return_value = frozenset()
        self.reject()
        self.command.assert_not_called()

    def test_ambiguous_started_retirement_is_not_retried(self):
        self.namespace.update(retirement_started=True, retirement_completed=False,
                              create_started=False)
        self.reject()
        self.container_inventory.assert_not_called()
        self.assertNotIn(["rm", CONTAINER_NAME], self.commands())

    def test_completed_retirement_is_not_repeated(self):
        self.namespace.update(retirement_started=True, retirement_completed=True,
                              create_started=False)
        self.execute()
        self.container_inventory.assert_not_called()
        self.assertNotIn(["rm", CONTAINER_NAME], self.commands())

    def test_absent_completed_resources_need_no_delete(self):
        self.container_inventory.return_value = self.image_inventory.return_value = frozenset()
        self.execute()
        self.command.assert_not_called()
        self.assertTrue(self.namespace["cleanup"])

    def test_container_rm_error_is_not_retried_and_other_cleanup_continues(self):
        self.command.side_effect = [OSError("synthetic removal failure"), (b"", 0, "0" * 64, 0)]
        self.reject()
