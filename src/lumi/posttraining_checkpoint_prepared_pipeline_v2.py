"""Internal generated-only pipeline, NOT a standalone qualification harness.

The caller independently authenticates all loaded sources/runtime, supplies two
separately owned fresh rootfs extractions and a private generator mountpoint,
excludes external writers and imposes an independent hard deadline. It retains
identity-tracked cleanup responsibility for both roots and external siblings,
INCLUDING failures partway through installation. This adapter neither supplies
that missing cleanup ledger nor acquires software, admits a host, authorizes
execution, starts a real import or accepts external model inputs/callbacks.

Private generated bytes remain in this process and never enter returned reports.
Even success means only two guardian passes, with whole-harness cleanup pending.
Tests replace native boundaries; no native qualification is claimed by tests.
"""

from __future__ import annotations

import os
import stat
import time
from pathlib import PurePosixPath

from . import posttraining_checkpoint_generator_guard_v2 as generator
from . import posttraining_checkpoint_generator_packet_v1 as codec
from . import posttraining_checkpoint_generator_sources_v1 as addon
from . import posttraining_checkpoint_prepared_controls_v1 as controls
from . import posttraining_checkpoint_prepared_launch_v2 as launcher
from . import posttraining_checkpoint_prepared_layout_v2 as layout
from .posttraining_final_base_metadata_v1 import canonical, sha

SCHEMA = "lumi.prepared-checkpoint-pipeline.v0.1"
MAXIMUM_SECONDS = 240
BUNDLE_KEYS = frozenset({"files", "manifest", "entry", "helper",
                        "expected_manifest_sha256", "expected_entry_sha256"})
NONCLAIMS = ("native_qualification_completed", "private_owned_cleanup_verified",
             "host_admission_verified", "runtime_origin_authenticated",
             "source_origin_authenticated", "external_writer_exclusion_verified",
             "execution_permitted", "full_size_import_authorized", "real_4b_import",
             "training_authorized", "production_eligible", "retry_allowed")
ERROR_CODES = frozenset({"runtime_rejected", "arguments_rejected", "binding_rejected",
                         "roots_rejected", "already_attempted", "generation_rejected",
                         "import_rejected", "deadline_exhausted", "pipeline_failed",
                         "cleanup_unconfirmed"})
_ATTEMPTED = False


class PreparedPipelineError(ValueError):
    def __init__(self, code="pipeline_failed"):
        self.code = code if type(code) is str and code in ERROR_CODES else "pipeline_failed"
        super().__init__(self.code)


def _need(value, code="arguments_rejected"):
    if not value:
        raise PreparedPipelineError(code) from None


def _bundle(value, *, for_generator):
    _need(type(value) is dict and set(value) == BUNDLE_KEYS, "binding_rejected")
    selected = addon.validate_bundle if for_generator else layout.sources.validate_bundle
    arguments = {key: value[key] for key in BUNDLE_KEYS if key != "helper"}
    if for_generator:
        arguments["helper"] = value["helper"]
    selected(**arguments)
    _need(type(value["helper"]) is bytes and len(value["helper"]) == addon.HELPER_BYTES
          and sha(value["helper"]) == addon.HELPER_SHA256, "binding_rejected")
    required = addon.REQUIRED_SOURCES if for_generator else layout.REQUIRED_SOURCES
    _need(required <= set(value["files"]), "binding_rejected")
    return dict(value, files=dict(value["files"]))


def _path(value):
    _need(type(value) is str and 0 < len(value) <= 4096
          and all(32 <= ord(char) < 127 for char in value), "roots_rejected")
    path = PurePosixPath(value)
    _need(path.is_absolute() and str(path) == value and ".." not in path.parts
          and 3 <= len(path.parts) <= 64 and not value.startswith("//"), "roots_rejected")
    return path


def _roots(first, second, mountpoint):
    _need(type(first) is type(second) is addon.rootfs.OwnedRootfs and first is not second,
          "roots_rejected")
    for owned in (first, second):
        owned._guard()
        _need(not owned._frozen and not owned._installed_files and not owned._installed_bytes,
              "roots_rejected")
        owned._verify_tree()
    first_path, second_path = _path(str(first._path)), _path(str(second._path))
    parents = [_path(str(owned._parent)) for owned in (first, second)]
    _need(first_path.parent == parents[0] and second_path.parent == parents[1]
          and parents[0] != parents[1]
          and not any(a in b.parents for a, b in (parents, parents[::-1])), "roots_rejected")
    parent_info = [os.fstat(owned._parent_fd) for owned in (first, second)]
    _need(all(stat.S_ISDIR(info.st_mode) and info.st_uid == info.st_gid == 0
              and stat.S_IMODE(info.st_mode) == 0o700 for info in parent_info)
          and (parent_info[0].st_dev, parent_info[0].st_ino)
              != (parent_info[1].st_dev, parent_info[1].st_ino), "roots_rejected")
    identities = [owned._nodes[()][0] for owned in (first, second)]
    _need(identities[0][:2] != identities[1][:2], "roots_rejected")
    point = _path(mountpoint)
    _need(point.parent == parents[0] and point != first_path, "roots_rejected")
    return str(first_path), identities[0]


def _stage_deadline(overall, *, reserve=0):
    now = time.monotonic_ns()
    _need(now < overall - reserve, "deadline_exhausted")
    return min(overall - reserve, now + 90_000_000_000)


def _generation(value, bundle, nonce):
    """Bind decoded maps back to their actual canonical private packet receipt."""
    try:
        _need(type(value) is dict and set(value) == {"private_data", "receipt"})
        private, receipt = value["private_data"], value["receipt"]
        _need(type(private) is dict and set(private) == {"metadata", "generated_inputs"})
        fixed = {"schema": generator.SCHEMA, "status": "passed", "synthetic_only": True,
            "owned_cgroups_empty_and_removed": 1, "kill_attempts": 1,
            "worker_exit_status_verified": True,
            "controller_and_deadline_watch_installed_before_release": True,
            "private_socket_buffers_verified": True,
            "worker_packet_maximum_bytes": generator.MAXIMUM_WORKER_PACKET_BYTES,
            "outer_packet_maximum_bytes": generator.MAXIMUM_PACKET_BYTES,
            "minimum_socket_buffer_bytes": generator.MINIMUM_SOCKET_BUFFER_BYTES,
            "memory_max_bytes": generator.LIMITS["memory_max_bytes"], "swap_max_bytes": 0,
            "pids_max": generator.LIMITS["pids_max"],
            "cpu_quota_us": generator.LIMITS["cpu_quota_us"],
            "cpu_period_us": generator.LIMITS["cpu_period_us"],
            "maximum_seconds": generator.MAXIMUM_SECONDS,
            "tmpfs_capacity_bytes": 536870912, "shm_capacity_bytes": 67108864,
            **dict.fromkeys(generator.NONCLAIMS, False)}
        _need(type(receipt) is dict
              and set(receipt) == set(fixed) | {"packet_receipt", "workload_processes_reaped"}
              and all(type(receipt[key]) is type(wanted) and receipt[key] == wanted
                      for key, wanted in fixed.items())
              and type(receipt["workload_processes_reaped"]) is int
              and 1 <= receipt["workload_processes_reaped"] <= 4)
        packet_receipt = receipt["packet_receipt"]
        generated = dict(private, receipt=packet_receipt["generation_receipt"])
        raw = codec.encode_generated_packet(generated,
            entry_sha256=bundle["expected_entry_sha256"],
            source_manifest_sha256=bundle["expected_manifest_sha256"],
            generation_nonce_sha256=nonce, source_report=packet_receipt["source_report"],
            copy_report=packet_receipt["copy_report"])
        decoded = codec.decode_generated_packet(raw,
            expected_entry_sha256=bundle["expected_entry_sha256"],
            expected_source_manifest_sha256=bundle["expected_manifest_sha256"],
            expected_generation_nonce_sha256=nonce)
        _need(canonical(decoded["receipt"]) == canonical(packet_receipt))
        source = packet_receipt["source_report"]
        _need(source["source_files_verified"] == len(bundle["files"])
              and source["source_bytes_verified"] == sum(map(len, bundle["files"].values()))
              and source["source_verification_read_bytes"] == source["source_bytes_verified"]
                  + len(bundle["manifest"]))
        return decoded
    except BaseException:
        raise PreparedPipelineError("generation_rejected") from None


def run_prepared_pipeline(*, generator_root, importer_root, generator_mountpoint_path,
                          generator_bundle, importer_bundle, generation_nonce_sha256,
                          base_script_path, expected_base_sha256, deadline_ns):
    """One generation followed by one import; never qualification or cleanup success."""
    global _ATTEMPTED
    _need(not _ATTEMPTED, "already_attempted")
    try:
        generator.child_bootstrap._runtime()
    except BaseException:
        raise PreparedPipelineError("runtime_rejected") from None
    try:
        gen = _bundle(generator_bundle, for_generator=True)
        imp = _bundle(importer_bundle, for_generator=False)
        environment = generator.child_bootstrap.validate_environment(
            dict(generator.child_bootstrap.FIXED_ENV,
                 LUMI_GENERATOR_ENTRY_SHA256=gen["expected_entry_sha256"],
                 LUMI_IMPORT_SOURCE_MANIFEST_SHA256=gen["expected_manifest_sha256"],
                 LUMI_GENERATION_NONCE_SHA256=generation_nonce_sha256))
        selected = _path(base_script_path)
        _need(selected.parts[-2:] == ("scripts", "run_sft_cgroup_fixture_v1.py")
              and expected_base_sha256 == generator.BASE_SHA256)
        now = time.monotonic_ns()
        _need(type(deadline_ns) is int and now + 120_000_000_000 <= deadline_ns
              <= now + MAXIMUM_SECONDS * 1_000_000_000)
        root_path, root_identity = _roots(generator_root, importer_root, generator_mountpoint_path)
        _stage_deadline(deadline_ns, reserve=90_000_000_000)
    except PreparedPipelineError:
        raise
    except BaseException:
        raise PreparedPipelineError("binding_rejected") from None
    _ATTEMPTED = True  # Before the first write; every later failure consumes this attempt.
    try:
        addon.install_generator_addon(generator_root, **gen)
        generated = generator.run_generator_guard(root_path, generator_mountpoint_path,
            root_identity, environment, base_script_path, expected_base_sha256,
            _stage_deadline(deadline_ns, reserve=90_000_000_000))
        decoded = _generation(generated, gen, generation_nonce_sha256)
        _stage_deadline(deadline_ns)
        prepared = controls.build_prepared_controls(metadata=decoded["metadata"],
            generation_nonce_sha256=generation_nonce_sha256,
            entry_sha256=imp["expected_entry_sha256"],
            source_manifest_sha256=imp["expected_manifest_sha256"],
            runtime_sources={name: imp["files"]["lumi/" + name] for name in controls.RUNTIME_NAMES})
        _stage_deadline(deadline_ns)
        installed = layout.install_prepared_layout(importer_root, **imp,
            control_raw=prepared["control_raw"], control_bodies=prepared["bodies"],
            generated_inputs=decoded["generated_inputs"],
            expected_control_sha256=sha(prepared["control_raw"]),
            expected_generation_nonce_sha256=generation_nonce_sha256)
        imported = launcher.launch_prepared_fixture(installed,
            expected_layout_sha256=sha(canonical(installed)),
            expected_manifest_sha256=imp["expected_manifest_sha256"],
            expected_entry_sha256=imp["expected_entry_sha256"],
            expected_control_sha256=sha(prepared["control_raw"]),
            expected_generation_nonce_sha256=generation_nonce_sha256,
            base_script_path=base_script_path, expected_base_sha256=expected_base_sha256,
            deadline_ns=_stage_deadline(deadline_ns))
        _need(imported["schema"] == launcher.SCHEMA
              and imported["status"] == "PASS_generated_fixture_guardian_verified"
              and imported["generation_nonce_sha256"] == generation_nonce_sha256
              and type(imported["owned_cgroups_empty_and_removed"]) is int
              and imported["owned_cgroups_empty_and_removed"] == 1, "import_rejected")
        _stage_deadline(deadline_ns)
        counts = decoded["receipt"]["generation_receipt"]
        _need(all(type(imported[key]) is int and imported[key] == counts[key]
                  for key in ("generated_input_files", "generated_input_bytes")), "import_rejected")
        return {"schema": SCHEMA, "status": "two_guardian_passes_completed_cleanup_pending",
            "synthetic_only": True, "generation_guard_launches": 1, "import_guard_launches": 1,
            "generation_nonce_sha256": generation_nonce_sha256,
            "generator_receipt_sha256": sha(canonical(generated["receipt"])),
            "import_receipt_sha256": sha(canonical(imported)),
            "control_sha256": sha(prepared["control_raw"]),
            "generated_input_files": counts["generated_input_files"],
            "generated_input_bytes": counts["generated_input_bytes"],
            "owned_cgroups_empty_and_removed": 2, "cleanup_required_on_success_and_failure": True,
            **dict.fromkeys(NONCLAIMS, False)}
    except PreparedPipelineError:
        raise
    except BaseException as error:
        if type(error) in (generator.GuardCompositionError, launcher.PreparedLaunchError) \
                and error.code in {"cleanup_unconfirmed", "deadline_exhausted"}:
            raise PreparedPipelineError(error.code) from None
        raise PreparedPipelineError("pipeline_failed") from None
